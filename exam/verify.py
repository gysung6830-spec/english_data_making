# 어휘 3종에는 자기검증을 걸지 않는다 — 일부러 뺀 것이라 여기 적어 둔다.
# 그 세 문항은 밑줄이 겹치면 안 되어 '차례로' 도는 직렬 구간(generators/vocab.
# generate_group)이고, 지문 생성의 최장 경로다. 다른 문항은 병렬이라 검증을 붙여도
# 벽시계 시간이 거의 늘지 않지만, 여기 붙인 한 번은 고스란히 대기 시간에 더해진다.
# 그래서 위험을 검증이 아니라 값이 0인 세 장치로 막는다:
#   · 원문단어형·부정어형 — 정답 아닌 밑줄을 원문 낱말로 되돌린다(_restore_original_marks).
#     원문 낱말은 필자가 쓴 말이라 어색할 수 없어, 정답이 둘이 될 길이 막힌다.
#   · 유의어형 — 오답 자리에 반의어가 들어갔는지 분석표로 센다(check_synonym_antonyms).
#   · 유의어형 프롬프트의 여섯 조항(표에서 먼저 고르기·굳은 연어 회피·어형 유지 등).
# 이것으로 다 막히지는 않는다. 실제 산출물에서 복수정답이 보이면 그때 다시 따진다.


def _base_key(type_key: str) -> str:
    """슬롯키(예: content_2)를 base(content)로 정규화 — 같은 유형을 여러 개 낼 때 대비."""
    return re.sub(r"_\d+$", "", type_key or "")

_SYS = ("너는 한국 수능식 영어 시험 문항 검수자다. 주어진 문항과 정답이 결함 없이 "
        "'유일 정답'으로 성립하는지 엄격하게 판정한다. 확신이 없으면 결함(ok=false)으로 본다.")


def enabled() -> bool:
    return os.environ.get("EXAM_NO_VERIFY", "") not in ("1", "true", "True")


def _text(html: str) -> str:
    """조판 HTML → 검증용 평문(태그 제거, 공백 정리)."""
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html or "")).strip()


def verify(client, type_key: str, q_html: str, a_html: str,
           max_retries: int = 1) -> tuple[bool, str]:
    """(ok, reason). 고위험 유형이 아니거나 검증 비활성/실패면 (True, '')로 통과 처리."""
    focus = HIGH_RISK.get(type_key) or HIGH_RISK.get(_base_key(type_key))
    if not focus or not enabled():
        return True, ""
    prompt = (
        f"[이 유형에서 집중 점검할 것]\n{focus}\n\n"
        f"[문제]\n{_text(q_html)}\n\n"
        f"[정답·해설]\n{_text(a_html)}\n\n"
        "위 정답이 유일하고 결함이 없으면 ok=true, reason 은 빈 문자열.\n"
        "복수정답·어법 오탐·내용 참거짓 오판 등 결함이 있으면 ok=false, reason 에 결함을 "
        "한국어 한 줄로 적어라."
    )
    try:
        from .tiering import VERIFY_EFFORT
        out: VerifyOut = client.structured(
            system=_SYS, prompt=prompt, model_cls=VerifyOut,
            max_tokens=600, max_retries=max_retries,
            effort=VERIFY_EFFORT)   # 검수는 언제나 깊게 — 마지막 문지기다
    except Exception:       # noqa: BLE001 — 검증 실패가 생성물을 버리게 하지 않는다
        return True, ""
    return bool(out.ok), (out.reason or "").strip()
