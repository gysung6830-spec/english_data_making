"""구문해석 실전서 카드 생성 프롬프트.

한 (코드, 기출 문장) 쌍마다 CardBody(오역/정답/팁)를 JSON 으로 강제 생성한다.
"""
from __future__ import annotations

SYSTEM = (
    "당신은 한국 수능·평가원 영어를 가르치는 20년차 구문해석 전문 강사입니다. "
    "평가원 문장은 추상적이고 수식어가 많아 학생이 '무슨 말인지' 놓치기 쉽습니다. "
    "당신의 임무는 특정 기능어(평가원 코드)가 든 문장을 보고, 학생이 흔히 저지르는 "
    "'오역'과 그것을 바로잡는 '올바른 해석 방향'을 짚어 주는 것입니다. "
    "요청된 JSON 스키마에 정확히 맞춰서만 응답하세요."
)


def card_prompt(cat_title: str, misread: str, code: str, code_ko: str,
                sentence: str) -> str:
    return (
        f"[카테고리] {cat_title}\n"
        f"[이 유형의 대표 오역] {misread}\n"
        f"[평가원 코드] {code}  (뜻: {code_ko})\n"
        f"[기출 문장]\n{sentence}\n\n"
        "위 문장에서 '평가원 코드'가 어떻게 쓰였는지 보고 다음을 작성하세요.\n"
        "- highlight: 문장 안에서 이 코드에 해당하는 부분을 '원문 그대로' 잘라 인용(수정 금지).\n"
        "- literal_trap: 이 코드를 무심코 직역/오해할 때 학생이 쓰게 되는 '틀린 해석'을 "
        "한 문장의 자연스러운 한국어로. (실제로 학생이 헷갈리는 지점을 재현)\n"
        "- trap_why: 그 해석이 왜 틀렸는지 방향·논리 근거를 한 줄로. "
        f"('{cat_title}' 유형의 함정과 연결해서)\n"
        "- correct: 문맥과 구조를 반영한 '올바른 해석'을 한 문장의 자연스러운 한국어로.\n"
        "- skeleton: 이 문장의 뼈대(핵심 주어+동사)만 아주 짧게. 없으면 빈 문자열.\n"
        "반드시 이 문장 자체에 근거해서 쓰고, 지어내지 마세요."
    )
