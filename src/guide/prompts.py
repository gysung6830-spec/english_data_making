def syntax_card_prompt(structure: str, how: str, sentence: str) -> str:
    return (
        f"[구문 유형] {structure}\n"
        f"[이 유형 괄호치는 법] {how}\n"
        f"[기출 문장]\n{sentence}\n\n"
        "이 문장을 '3단계 읽기'로 분석하세요. 중3 학생이 따라올 수 있게 아주 쉽게.\n"
        "- subject: 이 문장의 '주체(누가)' — 진짜 주어를 짧게.\n"
        "- action: 그 주체가 '무엇을 한다(행위)' — 진짜 동사+목적어를 짧게. (subject→action 으로 뼈대가 읽히게)\n"
        "- skeleton_en: 수식어(살)를 모두 뺀 '뼈대'만 남긴 영어 문장. 핵심 주어+동사(+목적어)만, 아주 짧게.\n"
        "- skeleton_ko: 그 뼈대의 중3 수준 쉬운 한국어 해석 한 줄.\n"
        "- modifiers: 괄호쳐야 할 수식어 덩어리들을 문장 등장 순서로. 각 항목:\n"
        "    · phrase(수식어 원문 그대로 인용), kind(관계사절/분사/전치사구/삽입/비교 중 하나),\n"
        "      connector(붙일 때 쓰는 연결어: ~하는/~하면서/~해서/~한 채로/~보다 등), meaning(그 수식어의 한국어 뜻).\n"
        "- full_ko: 뼈대에 수식어(살)를 연결어로 붙인, 자연스러운 완성 해석 한 문장.\n"
        "- real_meaning: 해석하면 이런 내용 — '이 문장 하나만으로' 도출되는 구체화 한 줄.\n"
        "  ★ 절대 규칙: 앞뒤 지문·필자 의도 끌어오지 말 것. 이 문장 안의 단어·구조만으로 알 수 있는 것만.\n"
        "  지시어 대상이 문장 밖이면 '(이것)'으로 두고 추측 금지. (다른 문장을 알아야 하면 쓰지 마세요.)\n"
        "- self_check: 학생이 스스로 괄호쳐 볼 수 있게 한 줄 힌트(선택, 없으면 빈 문자열).\n"
        "반드시 이 문장 자체에 근거해서 쓰고, 원문에 없는 내용을 지어내지 마세요."
    )


def card_prompt(cat_title: str, misread: str, code: str, code_ko: str,
                sentence: str) -> str:
    return (
        f"[카테고리] {cat_title}\n"
        f"[이 유형의 대표 오역] {misread}\n"
        f"[평가원 코드] {code}  (뜻: {code_ko})\n"
        f"[기출 문장]\n{sentence}\n\n"
        "위 문장에서 '평가원 코드'가 어떻게 쓰였는지 보고 다음을 작성하세요.\n"
        "- highlight: 문장 안에서 이 코드에 해당하는 부분을 '원문 그대로' 잘라 인용(수정 금지).\n"
        "- literal_trap: 이 코드를 무심코 직역/오해할 때 학생이 쓰게 되는 '틀린 해석'을 "
        "한 문장의 자연스러운 한국어로. (실제로 학생이 헷갈리는 지점을 재현)\n"
        "- trap_why: 그 해석이 왜 틀렸는지 방향·논리 근거를 한 줄로. "
        f"('{cat_title}' 유형의 함정과 연결해서)\n"
        "- correct: 문맥과 구조를 반영한 '올바른 해석'을 한 문장의 자연스러운 한국어로.\n"
        "- subject: 이 문장의 '주체(누가)' — 진짜 주어를 짧게.\n"
        "- action: 그 주체가 '무엇을 한다(행위)' — 진짜 동사+목적어를 짧게. (subject→action 으로 뼈대가 읽히게)\n"
        "- so_what: 해석하면 이런 내용 — '이 문장 하나만으로' 도출되는 구체화 한 줄.\n"
        "  ★ 절대 규칙: 앞뒤 지문이나 필자 의도를 끌어오지 말 것. 이 문장 안의 단어·구조만으로 알 수 있는 것만.\n"
        "  this/it/그 등 지시어가 가리키는 대상이 이 문장 안에 없으면, 그 부분은 '(이것)'으로 두고 추측하지 마세요.\n"
        "  (판별: '이게 이 문장만으로 나오나? 다른 문장을 알아야 하나?' → 후자면 쓰지 마세요.)\n"
        "- so_what_basis: 위 so_what을 '문장 속 어느 단서'에서 끌어냈는지 근거를 짧게. "
        "형식 '근거: {단서 유형}〈원문 조각〉'. 예: '근거: 동격〈regions of undifferentiated tissue〉'. "
        "동격·수식어(관계사/분사/전치사구)·예시(such as)·재진술(that is)·대조 중 무엇인지 밝히세요.\n"
        "- skeleton: 이 문장의 뼈대(핵심 주어+동사)만 아주 짧게. 없으면 빈 문자열.\n"
        "반드시 이 문장 자체에 근거해서 쓰고, 지어내지 마세요."
    )
