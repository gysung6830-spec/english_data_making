    "핵심 철학: '수능 문장 안에는 중3 문장이 숨어 있다. 수식어(살)를 괄호로 떼면 뼈대(주어+동사)만 남고, "
    "그 뼈대는 중3도 읽는다.' 이 원칙으로 문장을 분석합니다. "
