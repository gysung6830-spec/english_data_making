# ② 직독직해 ---------------------------------------------------------------
def literal_prompt(title: str, body: str) -> str:
    return (
        "아래 지문을 '직독직해' 자료로 만드세요. (왼쪽=영어+문법, 오른쪽=한글+단어 2단 구성용 데이터)\n"
        "- english: 각 문장의 '원문 전체'를 첫 단어부터 마침표까지 하나도 빠뜨리지 말고 그대로 적으세요.\n"
        "- 각 문장을 의미 단위(chunk)로 끊되, chunk 들을 순서대로 이으면 그 문장의 원문(english)과 "
        "'정확히 동일'해야 합니다. 특히 문장 맨 앞의 주어·동사를 절대 생략하지 말고 첫 chunk 에 포함하세요.\n"
        "  · (틀린 예) 원문이 'Conservation focuses on use, rather than ...' 인데 첫 chunk 를 "
        "'use, rather than ...' 로 시작 → 금지(맨 앞 'Conservation focuses on' 누락).\n"
        "  · (올바른 예) 첫 chunk = 'Conservation focuses on use,' 처럼 반드시 문장 맨 앞부터 시작.\n"
        "- 각 chunk 마다: english(원문 조각), syntax(핵심 구문/문법 분석, 예: '5형식 ask+목적어+to부정사', "
        "없으면 빈 문자열), korean(직독직해 한국어), words(그 chunk 의 핵심 단어와 뜻 목록).\n"
        "- 특히 관계사·분사·가정법·비교구문·도치·강조구문·5형식이 보이면 syntax 에 반드시 표시하세요.\n"
        "- note: 문장의 '내용 자체'가 너무 추상적이어서 직역만으로 이해가 어려운 경우에만, "
        "고등학생이 이해할 수 있는 쉬운 설명을 1문장 붙이세요. 그렇지 않으면 빈 문자열로 두세요.\n"
        "- translation: 그 문장 '전체'를 자연스러운 한국어로 매끄럽게 완역한 문장(직독직해가 아닌 완결된 해석).\n"
        "- sentences 배열에 문장 순서대로 담고, no 는 1부터 매깁니다.\n\n"
        + _passage_block(title, body)
    )


# ③ 핵심 문법 TOP 10 -------------------------------------------------------
def grammar_prompt(title: str, body: str) -> str:
    return (
        "아래 지문을 문장 단위로 앞에서부터 1,2,3... 번호를 매긴 뒤, "
        "각 문장에서 문법적으로 짚어줄 만한 사항이 있으면 '모두' 뽑으세요. (개수 제한 없음)\n"
        "- 문법 사항이 없는 문장은 건너뛰어도 됩니다. 한 문장에 여러 개면 여러 항목으로 나누세요.\n"
        "- 각 항목: no(전체 순번, 1부터), point(문법 포인트명), example(그 문장에서의 실제 예문), "
        "explanation(핵심 설명, 한국어), key(핵심 어법 여부 true/false), "
        "sentence_no(그 문법이 등장하는 문장 번호).\n"
        "- sentence_no 는 직독직해의 문장 번호와 반드시 일치시키세요.\n"
        "- 관계사·분사·가정법·비교구문·도치·강조구문·5형식 은 특히 중요하므로 빠뜨리지 말고 "
        "key=true 로 표시하세요. 나머지는 key=false.\n"
        "- 반드시 지문에서 실제로 쓰인 문법을 근거로 예문을 그대로 인용하세요.\n\n"
        + _passage_block(title, body)
    )


# ④ 어휘 -------------------------------------------------------------------
def vocab_prompt(title: str, body: str, lo: int, hi: int) -> str:
    return (
        f"아래 지문 전체에서 핵심 어휘를 {lo}개 이상 {hi}개 이하로 뽑아 정리하세요.\n"
        "- 우선순위 기준은 '어휘 문제(동의어·반의어·문맥상 의미)로 시험에 나오기 쉬운 단어'입니다. "
        "이 기준에 따라 품사는 동사 > 형용사 > 부사 순으로 우선해서 뽑되, "
        "지문의 주제·핵심 개념을 나타내는 '중요 명사'는 일부 포함해도 됩니다. "
        "다만 고유명사나 누구나 아는 아주 쉬운 일반명사는 제외하세요.\n"
        "- 특히 의미가 까다롭거나, 다의어이거나, 수준 높은 어휘, 유의어 구별이 중요한 단어를 우선합니다. "
        "누구나 아는 아주 쉬운 기초 단어는 넣지 마세요.\n"
        "- 먼저 지문을 문장 단위로 앞에서부터 1,2,3... 번호를 매기세요(직독직해의 문장 번호와 동일 기준).\n"
        "- 각 항목: no(1부터, 우선순위가 높은 것부터), word(단어/표현), meaning(한글 의미), "
        "synonyms(유의어), antonyms(반의어), "
        "sentence_no(그 단어가 지문에서 처음 나오는 문장 번호, 정수).\n"
        "- 유의어·반의어는 '아래 5가지를 모두 만족할 때만' 채우고, 하나라도 어긋나면 값을 '—'(대시 한 글자)로 두세요:\n"
        "   1) 문맥 일치 — 반드시 '지문에서 쓰인 그 뜻' 기준. "
        "(예: address가 '해결하다' 뜻이면 tackle·resolve 이고, '주소'가 아님)\n"
        "   2) 같은 품사·정확한 철자 — 동사↔동사, 형용사↔형용사, 명사↔명사. 스펠링이 정확해야 함.\n"
        "   3) 확실할 때만 — 애매하거나 부분적으로만 겹치면 억지로 넣지 말고 '—'. 칸당 1~2개까지만.\n"
        "   4) 쉬운 표준어 — 희귀어·과한 문어체 금지, 고등학생이 알 만한 단어로.\n"
        "   5) 반의어는 '진짜 반대 개념'만 — increase↔decrease 는 OK, increase↔stop 같은 건 금지.\n"
        "- 단어 선정 자체도 '유의어·반의어가 뚜렷한 어휘'를 우선하세요. "
        "유의어·반의어가 모두 애매해 '—'만 남을 단어는 되도록 빼고, "
        "유의어·반의어가 뚜렷한 '다른 확실한 핵심 어휘'로 대체하세요. "
        "('—'만 잔뜩인 목록보다, 유의어·반의어가 분명한 어휘 위주가 낫습니다. "
        "단, 지문의 핵심 개념어라면 '—'가 있더라도 포함해도 됩니다.)\n"
        "- 지문 길이에 비례해 개수를 정하되 반드시 위 범위를 지키세요.\n"
        "- english_summary: 지문 전체를 요약한 영어 문장으로, 핵심 단어를 최대한 많이 포함하되 "
        "무엇보다 '내용 이해'가 쉬워야 합니다. 1~2문장으로 쓰되, 필요하면 2문장으로 나누세요. "
        "한 문장에 분사구문을 여러 개 이어 붙여 지나치게 길고 복잡하게 만들지 말고, "
        "짧고 명확한 문장으로 자연스럽게 쓰세요.\n"
        "- english_summary_ko: 위 english_summary 문장을 자연스러운 한국어로 해석한 문장을 쓰세요.\n\n"
        + _passage_block(title, body)
    )


# ⑤ 구조 분석 --------------------------------------------------------------
def structure_prompt(title: str, body: str) -> str:
    return (
        "아래 지문의 '구조 분석'을 하세요.\n"
        "먼저 지문 유형을 판별합니다.\n"
        "- 비문학·논설문 등 논리 전개형이면 flow_type='logic' 으로 하고, "
        "stages 에 [도입]-[전개]-[상술]-[반론]-[결론] 같은 논리 구조를 단락별로 정리하세요.\n"
        "- 문학·일상문 등 감정 전개형이면 flow_type='emotional' 로 하고, "
        "감정 변화 단계(예: 5단계)로 정리하되 각 단계에 감정명(stage)을 넣으세요.\n"
        "- content 는 시험 직전에 내용만 훑어볼 수 있도록 '~함', '~임' 같은 개조식으로 아주 간단히 쓰세요.\n"
        "- 숫자·수치를 개조식에 넣을 때는 원문 값을 자릿수까지 '그대로' 옮기세요"
        "(예: 445 billion=4450억, 15 billion=150억). 큰 수를 임의로 줄여 자릿수를 바꾸지 마세요.\n"
        "- 먼저 지문을 문장 단위로 앞에서부터 1,2,3... 번호를 매기고(직독직해와 동일 기준), "
        "가장 마지막 문장의 번호(=전체 문장 수)를 확인하세요.\n"
        "- evidence 에는 영어 문장을 인용하지 말고, 해당 단계가 지문의 몇 번째 문장인지만 "
        "'문장 3', '문장 3~5' 형태로 적으세요. "
        "이때 문장 번호는 '전체 문장 수를 절대 넘지 않게' 하세요"
        "(예: 지문이 51문장이면 '문장 49~51'까지만 가능, '문장 49~55'처럼 넘기지 말 것).\n"
        "- genre_reason 에 왜 그 유형으로 판별했는지 한 줄로 쓰세요.\n"
        "- easy_explanation 에는 이 지문의 핵심을 학생이 이해하기 쉽게 한 문장으로 정리하세요. "
        "과장된 유행어·이모지·인터넷 말투 없이, 담백하고 자연스러운 설명체로 쓰세요.\n"
        "- examples 에는 지문 내용을 실생활에 빗댄 예시를 1~2개 넣으세요. "
        "'~임', '~거임', '~하는 원리임' 같은 구어체나 억지스러운 유행어를 쓰지 말고, "
        "'~와 같다', '~하는 것과 비슷하다'처럼 담백하고 자연스러운 설명문(교사 말투)으로 쓰세요.\n\n"
        + _passage_block(title, body)
    )


# ⑥ 출제 포인트 ------------------------------------------------------------
def exam_prompt(title: str, body: str, grammar: schemas.GrammarSection | None,
                vocab: schemas.VocabSection | None) -> str:
    ref = ""
    if grammar:
        pts = ", ".join(g.point for g in grammar.items[:6])
        ref += f"\n[참고: 앞서 뽑은 핵심 문법] {pts}"
    if vocab:
        ws = ", ".join(v.word for v in vocab.items[:8])
        ref += f"\n[참고: 앞서 뽑은 핵심 어휘] {ws}"
    return (
        "아래 지문의 '치밀하게 분석한 출제 포인트'를 만드세요. "
        "출제 유형은 반드시 다음 3가지로만, 이 순서대로 한 항목씩 구성합니다(다른 유형 금지):\n"
        "  1) 지칭추론(대명사)  2) 함축의미  3) 서술형\n"
        "- 각 항목: question_type(위 3개 중 하나), content(아래 형식대로 상세히, 여러 줄이면 줄바꿈 \\n 으로 구분). "
        "tip 은 빈 문자열로 두세요.\n"
        "- 먼저 지문을 문장 단위로 앞에서부터 1,2,3... 번호를 매겨 두고, 아래에서 그 번호를 사용하세요.\n\n"
        "[지칭추론] 지문에 나오는 '모든' 대명사·지시어(it, its, this, that, these, those, they, them, "
        "their, one, which 등)를 빠짐없이 문장 순서대로 골라, 각각이 가리키는 대상을 밝히세요"
        "(시험 출제 가능성과 무관하게 전부). 각 줄 형식:\n"
        "   '{문장번호}문장 - {대명사} - ({그 대명사가 가리키는 대상})'\n"
        "   예: '4문장 - those - (the perspectives of administration personnel)'\n"
        "   · 가운데 칸에는 대명사·지시어 '한 단어'만 적으세요(it/its/they/them/their/this/that/which/one 등). "
        "구·절이나 설명 문구를 넣지 말고, '한 줄에 대명사 하나'만 다루세요.\n"
        "   · 대상(괄호 안)은 가리키는 것을 '짧은 명사구'로만 적으세요(문장 전체를 통째로 넣지 말 것).\n"
        "   · 가주어·가목적어·비인칭 it 처럼 특정 대상을 가리키지 않으면 대상 자리에 "
        "'가주어(진주어 to~)', '비인칭 it' 처럼 그 역할을 짧게 적으세요.\n"
        "   · 같은 대명사가 여러 문장에 나오면 각 문장마다 따로 한 줄씩 적으세요.\n\n"
        "[함축의미] 직독직해(단순 직역)만으로 바로 이해되는 표현은 '모두 제외'하세요. "
        "오직 지문 전체의 내용·맥락을 알아야만 뜻이 풀리는 구문·표현만 고르세요. "
        "고른 표현마다 아래 4줄을 순서대로 쓰고, 표현이 여러 개면 표현과 표현 사이를 '빈 줄'로 구분하세요 "
        "(줄바꿈은 \\n):\n"
        "   {문장번호}문장 \"{원문 표현}\"\n"
        "   · 원문 표현은 문장 전체가 아니라, 함축이 걸리는 '핵심이 되는 짧은 구·숙어·비유 표현'만 "
        "따옴표로 인용하세요(대략 2~7단어). 문장을 통째로 넣지 말 것.\n"
        "   · 문맥상 의미: {지문 내용을 알아야만 풀리는 한글 의미}\n"
        "   · 영어 정답 표현: {실제 시험 선지처럼 자연스러운 영어 패러프레이즈 한 줄}\n"
        "   ⚠️ 직역 함정: {그대로 직역하면 왜 오답인지 한 줄로}\n"
        "   ※ 직역으로 뜻이 그대로 드러나는(직독직해로 알 수 있는) 표현은 절대 넣지 마세요.\n\n"
        "[서술형] 지문 전체에서 '문법 요소가 가장 많고 영작하기 가장 어려운' 문장을 딱 '하나만' 고르세요. "
        "(items 에 서술형 항목은 1개만)\n"
        "   - content 는 정확히 두 줄로, 줄바꿈 \\n 으로 구분합니다.\n"
        "     · 첫째 줄: 그 문장을 영어 원문 '그대로'(수정·축약 금지) 적습니다.\n"
        "     · 둘째 줄: 그 문장에 쓰인 어려운 문법 요소들을 쉼표로 나열합니다(영작이 어려운 근거).\n"
        "   - 형식: '{원문 문장 그대로}\\n{문법요소1, 문법요소2, ...}'\n"
        "   - 선정 기준: 5형식, 분사구문, 관계부사, 강조구문, 가정법, 비교구문 등 어려운 문법.\n"
        + ref + "\n\n"
        + _passage_block(title, body)
    )
