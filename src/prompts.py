        "- theme_en: 위 theme_ko 를 영어로 옮긴 '짧은 영어 명사구' 제목(각 단어 첫 글자 대문자). "
        "반드시 theme_ko 와 '의미가 매칭'되어야 하며, 가능한 한 지문에 실제로 나온 영어 단어·표현을 "
        "사용해 번역하세요(예: theme_ko '소유가 많아질수록 공유를 덜하게 되는 경향' → "
        "'The Tendency to Share Less as We Own More').\n"
        "- keywords: 위 overall 문장에서 주제의 핵심을 이루는 '가장 중요한 키워드' 2~4개를 고르세요. "
        "반드시 overall 문장 안에 '있는 그대로'의 표현(부분 문자열)으로 적어야 하며(강조 표시에 사용), "
