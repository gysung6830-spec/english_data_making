        "- 각 chunk 마다: english(원문 조각), syntax(핵심 구문/문법 분석, 예: '5형식 ask+목적어+to부정사', "
        "없으면 빈 문자열), korean(직독직해 한국어), words(그 chunk 의 핵심 단어와 뜻 목록).\n"
        "- 특히 관계사·분사·가정법·비교구문·도치·강조구문·5형식이 보이면 syntax 에 반드시 표시하세요.\n"
