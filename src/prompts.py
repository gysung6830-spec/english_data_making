def extract_prompt(raw_text: str) -> str:
    return (
        "다음은 PDF 에서 추출된 원문 텍스트입니다. 이 안에서 '영어 지문 본문'만 식별하여 "
        "제목(title), 출처(source, 없으면 빈 문자열), 그리고 문단 목록(paragraphs)으로 정리하세요.\n"
        "- 문제/보기/정답/해설/어휘표는 절대 포함하지 마세요.\n"
        "- 본문 문단은 원문 그대로(영어), 문단 단위로 나누어 배열에 담으세요.\n"
        "- 제목이 명확하지 않으면 본문 내용을 대표하는 짧은 영어 제목을 지어 넣으세요.\n\n"
        f"[원문 텍스트]\n{raw_text}"
    )


def _passage_block(title: str, body: str) -> str:
    return f"[지문 제목] {title}\n\n[지문 본문]\n{body}"


# ① 요약 -------------------------------------------------------------------
def summary_prompt(title: str, body: str) -> str:
    return (
        "아래 지문의 '주제'를 딱 한 문장으로 정리하세요.\n"
        "- overall: 지문 전체를 관통하는 주제를 담은 한 문장(한국어). 문단별 요약은 하지 마세요.\n\n"
        + _passage_block(title, body)
    )


# ② 직독직해 ---------------------------------------------------------------
def literal_prompt(title: str, body: str) -> str:
    return (
        "아래 지문을 '직독직해' 자료로 만드세요. (왼쪽=영어+문법, 오른쪽=한글+단어 2단 구성용 데이터)\n"
        "- 각 문장을 의미 단위(chunk)로 끊습니다.\n"
        "- 각 chunk 마다: english(원문 조각), syntax(핵심 구문/문법 분석, 예: '5형식 ask+목적어+to부정사', "
        "없으면 빈 문자열), korean(직독직해 한국어), words(그 chunk 의 핵심 단어와 뜻 목록).\n"
        "- 특히 관계사·분사·가정법·비교구문·도치·강조구문·5형식이 보이면 syntax 에 반드시 표시하세요.\n"
        "- note: 문장의 '내용 자체'가 너무 추상적이어서 직역만으로 이해가 어려운 경우에만, "
        "고등학생이 이해할 수 있는 쉬운 설명을 1문장 붙이세요. 그렇지 않으면 빈 문자열로 두세요.\n"
        "- sentences 배열에 문장 순서대로 담고, no 는 1부터 매깁니다.\n\n"
        + _passage_block(title, body)
    )


# ③ 핵심 문법 TOP 10 -------------------------------------------------------
def grammar_prompt(title: str, body: str) -> str:
    return (
        "아래 지문을 문장 단위로 앞에서부터 1,2,3... 번호를 매긴 뒤, "
        "각 문장에서 문법적으로 짚어줄 만한 사항이 있으면 '모두' 뽑으세요. (개수 제한 없음)\n"
        "- 문법 사항이 없는 문장은 건너뛰어도 됩니다. 한 문장에 여러 개면 여러 항목으로 나누세요.\n"
        "- 각 항목: no(전체 순번, 1부터), point(문법 포인트명), example(그 문장에서의 실제 예문), "
        "explanation(핵심 설명, 한국어), key(핵심 어법 여부 true/false), "
        "sentence_no(그 문법이 등장하는 문장 번호).\n"
        "- sentence_no 는 직독직해의 문장 번호와 반드시 일치시키세요.\n"
        "- 관계사·분사·가정법·비교구문·도치·강조구문·5형식 은 특히 중요하므로 빠뜨리지 말고 "
        "key=true 로 표시하세요. 나머지는 key=false.\n"
        "- 반드시 지문에서 실제로 쓰인 문법을 근거로 예문을 그대로 인용하세요.\n\n"
        + _passage_block(title, body)
    )


# ④ 어휘 -------------------------------------------------------------------
def vocab_prompt(title: str, body: str, lo: int, hi: int) -> str:
    return (
        f"아래 지문에서 핵심 어휘를 {lo}개 이상 {hi}개 이하로 뽑아 정리하세요.\n"
        "- 각 항목: no(1부터), word(단어/표현), meaning(한글 의미), "
        "synonyms(유의어, 없으면 빈 문자열), antonyms(반의어, 없으면 빈 문자열), "
        "example(지문 속 예문).\n"
        "- 지문 길이에 비례해 개수를 정하되 반드시 위 범위를 지키세요.\n"
        "- english_summary: 위에서 뽑은 핵심 단어들을 최대한 많이 포함하는, 지문 전체를 요약한 "
        "2문장 이내의 영어 문장을 작성하세요. 자연스러운 영어로 쓰되 핵심 어휘가 실제로 들어가야 합니다.\n\n"
        + _passage_block(title, body)
    )


# ⑤ 구조 분석 --------------------------------------------------------------
def structure_prompt(title: str, body: str) -> str:
    return (
        "아래 지문의 '구조 분석'을 하세요.\n"
        "먼저 지문 유형을 판별합니다.\n"
        "- 비문학·논설문 등 논리 전개형이면 flow_type='logic' 으로 하고, "
        "stages 에 [도입]-[전개]-[상술]-[반론]-[결론] 같은 논리 구조를 단락별로 정리하세요.\n"
        "- 문학·일상문 등 감정 전개형이면 flow_type='emotional' 로 하고, "
        "감정 변화 단계(예: 5단계)로 정리하되 각 단계에 감정명(stage)을 넣으세요.\n"
        "- content 는 시험 직전에 내용만 훑어볼 수 있도록 '~함', '~임' 같은 개조식으로 아주 간단히 쓰세요.\n"
        "- evidence 에는 영어 문장을 인용하지 말고, 해당 단계가 지문의 몇 번째 문장인지만 "
        "'문장 3', '문장 3~5' 형태로 적으세요.\n"
        "- genre_reason 에 왜 그 유형으로 판별했는지 한 줄로 쓰세요.\n"
        "- easy_explanation 에는 이 지문의 핵심을 학생이 확 와닿게 친근한 구어체 한 문장으로 요약하세요.\n"
        "- examples 에는 지문 내용을 실생활 상황에 빗댄 공감형 예시를 1~2개 넣으세요. "
        "'~하는 거랑 똑같음', '~하는 원리임' 같은 학생 친화적 말투로 생생하게 쓰되, 지나친 비속어는 피하세요.\n\n"
        + _passage_block(title, body)
    )


# ⑥ 출제 포인트 ------------------------------------------------------------
def exam_prompt(title: str, body: str, grammar: schemas.GrammarSection | None,
                vocab: schemas.VocabSection | None) -> str:
    ref = ""
    if grammar:
        pts = ", ".join(g.point for g in grammar.items[:6])
        ref += f"\n[참고: 앞서 뽑은 핵심 문법] {pts}"
    if vocab:
        ws = ", ".join(v.word for v in vocab.items[:8])
        ref += f"\n[참고: 앞서 뽑은 핵심 어휘] {ws}"
    return (
        "아래 지문의 '내신 빈출 출제 포인트 체크리스트'를 표 형태 데이터로 만드세요.\n"
        "- 출제 유형은 반드시 다음 4가지로만, 이 순서대로 한 항목씩 구성하세요(다른 유형 금지):\n"
        "  1) 지칭추론(대명사)  2) 어휘  3) 순서배열·문장삽입  4) 서술형\n"
        "- 각 항목: question_type(위 4개 중 하나), content(그 유형으로 이 지문에서 어떻게 출제될지), "
        "tip(은아 T tip: 변형 대비 포인트).\n"
        "- '지칭추론'은 this/that/those/it 등 대명사·지시어가 가리키는 대상을, "
        "'순서배열·문장삽입'은 연결어(However, Similarly, In addition 등)와 지시어 단서를 활용하세요.\n"
        "- 위 [참고]로 준 어휘·문법을 재사용하여 일관성 있게 작성하세요.\n"
        + ref + "\n\n"
        + _passage_block(title, body)
    )
