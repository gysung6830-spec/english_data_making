"""빈칸형 워크북 LLM 프롬프트 (유형 B 지문 빈칸 + 유형 A 요약문 빈칸)."""
from __future__ import annotations

SYSTEM = (
    "당신은 한국 고등학교 영어 내신 빈칸 워크북 출제 전문가다. "
    "한 지문으로 '지문 빈칸형'과 '요약문 빈칸형'을 만든다. "
    "요청된 JSON 스키마에 정확히 맞는 JSON 으로만 응답한다."
)

_RULES = """[유형 B — 지문 빈칸형]
- 원문 지문을 '그대로' 두고, 학습상 핵심 단어를 빈칸으로 뚫는다. 빈칸 자리에는 {{B1}}, {{B2}} … 를 넣는다.
- 빈칸은 '지문당 최대 10개'. 단, '모든 문장에 최소 1개'의 빈칸을 반드시 둔다.
  먼저 각 문장에서 1개씩 확보한 뒤, 남는 자리를 아래 우선순위로 채워 최대 10개까지 뽑는다:
  1) 핵심 동사  2) 핵심 준동사(to부정사·동명사·분사)  3) 핵심 형용사  4) 핵심 부사
  5) 명사는 '이 글의 핵심어(주제어)'일 때만 후보에 포함.
  (문장 수가 10을 넘으면 '문장당 1개'를 우선한다.)
- 관사·전치사·접속사·대명사 등 기능어와 3자 미만 단어는 되도록 피하되, 그 문장에 마땅한 후보가 없으면
  가장 학습 가치가 높은 단어 1개를 골라 반드시 빈칸을 만든다.
- 각 문장은 원문 순서대로 sentences 에 담고(no 1부터), en_template 은 원문 그대로에 {{Bn}} 만 삽입한다.
- blanks 의 answer 는 그 자리의 '원래 단어'다. '모든 문장'이 최소 1개의 blanks 를 가져야 한다.
- ko 에는 그 문장의 한국어 해석을 넣는다(입력에 해석이 있으면 그대로, 없으면 생성).

[유형 A — 요약문 빈칸형]
- 원문을 '다른 표현으로 바꿔 쓴' 요약문(패러프레이징)을 새로 만든다. 원문 어휘를 그대로 복사하지 말 것.
- 길이는 원문의 30~50% 수준.
- 요약문의 핵심어를 빈칸으로 뚫고 자리에 {{S1}}, {{S2}} … 를 넣어 summary_template 에 담는다.
- summary_blanks 의 answer 는 그 자리에 들어갈 정답 단어다(요약문 속 단어, 원문과 달라도 됨).
- 빈칸은 5개 안팎으로 한다. (단어뱅크는 코드가 정답만 모아 자동 생성하므로 오답을 만들지 말 것.)

[공통]
- {{Bn}}·{{Sn}} 자리표시자는 각각 blanks·summary_blanks 와 '정확히 1:1'로 대응해야 한다.
- 다른 말 없이 JSON 만 출력한다."""


def blanks_prompt(title: str, body: str, ko: str = "") -> str:
    block = f"[지문 제목] {title}\n\n[지문 본문]\n{body}"
    if ko and ko.strip():
        block += f"\n\n[해석]\n{ko.strip()}"
    else:
        block += "\n\n[해석] (없음 — 문장별로 자연스러운 한국어 해석을 직접 생성)"
    return (
        "아래 영어 지문으로 '빈칸형 워크북' 한 세트(유형 B → 유형 A)를 만든다.\n"
        "출력은 하나의 세트(LLMBlankSet) JSON 이다. no 는 1, title 은 지문 제목, subtitle 은 한 줄 요지.\n\n"
        + _RULES + "\n\n" + block
    )
