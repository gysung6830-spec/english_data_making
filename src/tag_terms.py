"""어법칩 태그 표준화 — 표준 어법 용어로 통일(용어만), 숙어·구문은 보존."""
import re, json, glob
# 표준 태그 정규화: 별칭/변형 → 표준 용어(용어만, 문장 속 단어 제거)
RULES=[
 (r'가목적어|진목적어', '가목적어-진목적어'),
 (r'가주어|진주어', '가주어-진주어'),
 (r'사역', '사역동사'),
 (r'지각', '지각동사'),
 (r'5형식|목적격\s*보어|SVOC', '5형식 목적격보어'),
 (r'전치사\s*\+?\s*관계', '전치사+관계대명사'),
 (r'계속적', '관계사 계속적 용법'),
 (r'관계부사', '관계부사'),
 (r'\bwhat\b|관계대명사\s*what', '관계대명사 what'),
 (r'관계대명사|관계사', '관계대명사'),
 (r'분사구문', '분사구문'),
 (r'감정\s*(분사|수동)', '감정분사'),
 (r'분사.*(수식|형용사)|과거분사|현재분사|후치\s*수식', '분사 형용사적 용법'),
 (r'동명사', '동명사'),
 (r'원형\s*부정사', '원형부정사'),
 (r'to\s*부정사|부정사', 'to부정사'),
 (r'명사절', '명사절 that'),
 (r'부사절', '부사절'),
 (r'완료\s*수동', '완료 수동태'),
 (r'수동', '수동태'),
 (r'과거완료', '과거완료'),
 (r'현재완료', '현재완료'),
 (r'진행', '진행형'),
 (r'the\s*비교급.*the|the\s*\S*er.*the', 'the 비교급 the 비교급'),
 (r'비교급\s*강조|강조.*비교급|much.*비교급', '비교급 강조'),
 (r'최상급', '최상급'),
 (r'원급', '원급비교'),
 (r'비교', '비교급'),
 (r'도치', '도치'),
 (r'강조\s*구문|it[- ]?that|it.*that.*강조', 'it-that 강조구문'),
 (r'동격', '동격 that'),
 (r'가정법', '가정법'),
 (r'병렬|대등|등위', '병렬구조'),
 (r'부분부정', '부분부정'),
 (r'상관\s*접속사|not\s*only|either|neither', '상관접속사'),
 (r'대동사', '대동사'),
 (r'생략', '공통요소 생략'),
 (r'대명사|대용|지시', '지시·대용어'),
 (r'부사\s*위치|부사구', '부사(구)'),
 (r'4형식', '4형식'),
 (r'2형식', '2형식'),
 (r'3형식', '3형식'),
]
def normalize_tag(tag):
    t=tag.strip()
    for pat,canon in RULES:
        if re.search(pat, t, re.I): return canon
    # 표준 범주 밖: 한글로 시작하면 뒤 영어 표지어 제거(용어만), 영어로 시작(숙어·구문)이면 보존
    if re.match(r'^[가-힣]', t):
        t2=re.sub(r'\s*\([^)]*[A-Za-z][^)]*\)\s*$','',t)   # 뒤 (영어) 괄호 제거
        t2=re.sub(r'\s+[A-Za-z][A-Za-z0-9\'’.~+/ -]*$','',t2)  # 뒤 영어 표지어 제거
        return t2.strip() or t
    return t
