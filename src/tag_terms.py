def normalize_tag(tag):
    t=tag.strip()
    for pat,canon in RULES:
        if re.search(pat, t, re.I): return canon
    # 표준 범주 밖: 한글로 시작하면 뒤 영어 표지어 제거(용어만), 영어로 시작(숙어·구문)이면 보존
    if re.match(r'^[가-힣]', t):
        t2=re.sub(r'\s*\([^)]*[A-Za-z][^)]*\)\s*$','',t)   # 뒤 (영어) 괄호 제거
        t2=re.sub(r'\s+[A-Za-z][A-Za-z0-9\'’.~+/ -]*$','',t2)  # 뒤 영어 표지어 제거
        return t2.strip() or t
    return t
