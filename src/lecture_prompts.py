"""'강의컨셉 교재(필생보)' 생성 프롬프트.

구성: ① 어휘 리스트 → ② 문장별(끊어읽기 빈칸 채우기 + 내용 객관식) → ③ 글 예측.
- 학생은 '틀리기 쉬운 부분'만 빈칸으로 채우고, 각 문장 내용을 객관식으로 확인한다.
- 문장 번호(1..n)는 코드가 매겨 프롬프트에 넣어 주고, LLM 은 그 번호를 그대로 사용한다.
- 응답은 구조화된 JSON(스키마)으로 강제한다. 지문에 실제로 있는 내용만 쓴다.
- 2단계 호출: (1) 개관(Overview) → (2) 문장별 분석(SentenceAnalysis).
"""
from __future__ import annotations

from .lecture_schemas import STANCES, STRUCTURES, LectureSentence

SYSTEM = (
    "당신은 한국 고등학교 영어 내신·수능 지문으로 '필자의 생각이 보이는 영어독해' 워크북을 "
    "만드는 전문 강사입니다. 학생이 어휘를 익히고, 각 문장에서 틀리기 쉬운 부분만 빈칸으로 채우고, "
    "문장 내용을 객관식으로 확인한 뒤, 지문 전체를 예측하도록 설계합니다. 담백하고 자연스러운 "
    "설명체를 쓰고, 지문에 실제로 있는 내용만 근거로 하며, 요청된 JSON 스키마에 정확히 맞는 "
    "JSON 으로만 응답하세요."
)


def _numbered(sentences: list[LectureSentence]) -> str:
    return "\n".join(f"{s.id} {s.text}" for s in sentences)


# 1차: 지문 전체 개관(③ 글 예측 정답) ----------------------------------------
def overview_prompt(title: str, sentences: list[LectureSentence]) -> str:
    n = len(sentences)
    return (
        f"[지문 제목] {title}\n\n"
        f"[지문 — 문장 번호가 매겨져 있음 (총 {n}문장)]\n{_numbered(sentences)}\n\n"
        "위 지문의 '글 예측 정답'을 만드세요.\n\n"
        "- theme_ko: 이 지문의 주제를 나타내는 '한글 명사구' 제목"
        "(예: '두려움이 영장류·아기의 사회성 발달을 늦추는 이유'). 완결 문장이 아니라 제목다운 명사구.\n"
        "- key_grammar(🔑 이 지문의 핵심 문법 1개): 이 지문에서 '가장 어렵고 핵심적인 문법 1개'를 골라 "
        "학생이 제대로 이해하도록 '충실한 미니 강의'로 구성하세요(빈약하지 않게).\n"
        "  {point(문법명, 예: '관계사 that의 삽입', '비교급 than절의 도치·생략'),\n"
        "   explanation(그 문법을 '항목별로 나눠' 쉽게 설명한 3~5줄 리스트. 각 줄은 한 가지 포인트만 "
        "담아 짧게 — 예: '형태(어순)', '왜/언제 쓰나', '겹치는 말 생략', '자주 하는 실수·주의', '해석 요령' "
        "등을 나눠서. 각 줄에서 학생이 채우도록 '핵심어' 1개 정도를 [[ ]]로 감싸세요),\n"
        "   example(지문 속 실제 예를 짧게 인용),\n"
        "   example_analysis(그 지문 예를 이 문법 관점에서 한 줄로 분석 — 무엇이 도치/생략/수식됐는지),\n"
        "   drills(연습문제 2~4개: 해석과 영작을 '섞어서'. 각 {kind:'해석' 또는 '영작', "
        "question(해석=이 문법이 쓰인 '영어 문장', 영작=영어로 옮길 '한국어 문장'), answer(모범 답)}). "
        "쉬운 것부터 조금씩 어렵게, 지문과 비슷한 난이도의 예문으로.)}.\n"
        "- topic(🔎 소재): 이 지문이 '무엇에 관한 글인지' 한 줄로.\n"
        f"- stance(🗣 필자 의견): 다음 중 하나만 — {' / '.join(STANCES)}.\n"
        "- stance_reason: 평가어(형용사)·마지막 문장 등 근거를 한 줄로.\n"
        f"- structure(🧩 글의 구조): 다음 중 하나만 — {' / '.join(STRUCTURES)}.\n"
        "- structure_reason: 그렇게 본 근거를 전환·연결표현이나 문장 번호로 한 줄.\n"
        "- restatement_chains(🔗 재진술 사슬): '필자의 핵심 의견을 이루는 개념'이 지문에서 "
        "'서로 다른 영어 표현'으로 다시 나오는 사슬만 담으세요. 실제로 존재하는 것만, 억지로 지어내지 "
        "마세요(없으면 1개만, 최대 2개). 각 사슬: label(개념의 '한글' 이름, 예: '두려움을 느끼는 아기'), "
        "expressions(지문에 실제로 나온 '영어' 표현들을 순서대로 2개 이상 — 반드시 위 지문에 있는 "
        "'그대로의 표현'을 복사해서 넣으세요. 지문에서 형광펜으로 찾아 표시할 수 있어야 합니다), "
        "variation(그 표현들이 추상→구체 등 어떻게 바뀌어 가는지 한 줄 한국어 설명).\n"
        "- flow_blocks(📝 글 내용 정리 = 글 순서): 지문을 의미 단위로 '3~6개 블록'으로 나눠 흐름을 "
        "정리하세요. 각 블록: stage(그 블록의 역할 — 도입/전개/사례/조건/전환/확장/결론 등에서 알맞게), "
        "sentence_range(그 블록의 문장 번호 범위, 예: '1~2', '6'), summary(그 블록 내용을 한 줄로 요약. "
        "가장 핵심이 되는 '단어' 1~2개를 [[ ]]로 감싸세요 — 학생용에서 그 단어가 빈칸이 됩니다), "
        "easy_example(그 블록을 쉬운 일상 비유로 한 줄). 블록들을 이으면 지문 전체 흐름이 됩니다.\n"
    )


# 2차: 어휘 + 문장별 끊어읽기/내용 ------------------------------------------
def sentence_prompt(title: str, sentences: list[LectureSentence]) -> str:
    n = len(sentences)
    return (
        f"[지문 제목] {title}\n\n"
        f"[지문 — 문장 번호가 매겨져 있음 (총 {n}문장)]\n{_numbered(sentences)}\n\n"
        f"위 {n}개 문장을 '한 문장도 빠짐없이(id 1~{n} 전부)' 분석해 sentences 배열에 순서대로 담으세요.\n"
        "각 문장 항목:\n"
        "- id: 위 문장 번호 그대로.\n"
        "- english: 그 문장의 원문 전체를 첫 단어부터 마침표까지 그대로.\n"
        "- grammar: 그 문장에서 '중요한 어법 포인트' 1~3개를 {tag, note}로. tag 는 짧은 어법명"
        "(예: '관계사 that', '분사구문', '비교급 than절 도치·생략', 'serve to+동사원형'), "
        "note 는 학생이 바로 이해할 간단한 설명 한 줄(예: '앞의 the role 을 that절이 수식'). "
        "짚을 어법이 없으면 빈 배열.\n"
        "- vocab: 그 문장에서 뽑을 핵심 어휘 2~5개를 {word, meaning}로. '중·고등 수준' 어휘만 담고 "
        "누구나 아는 아주 쉬운 기초 단어(초등 수준)는 제외하세요. 다의어·수준 높은 단어와 함께 "
        "'숙어·구동사(예: seek out, play a role in, serve to, keep up with)'도 적극 포함하세요"
        "(숙어는 word 에 표현 그대로). (맨 위 '어휘 리스트'로 모읍니다.)\n"
        "- chunks(끊어읽기): 문장을 의미 단위로 끊어 각 조각을 {en, ko}로. en 을 순서대로 이으면 그 "
        "문장의 english 와 정확히 같아야 하고(맨 앞 주어·동사를 첫 chunk 에 포함), ko 는 그 조각만의 "
        "직독직해입니다.\n"
        "  · 빈칸 출제원리(★): 각 조각에서 '해석하기 어렵거나 오역 위험이 큰 부분'을 골라, en 에서 그 "
        "영어 부분을 [[ ]]로 감싸고 ko 에서도 대응하는 한국어 부분을 [[ ]]로 감싸세요. 학생용에서는 "
        "ko 의 [[ ]] 부분이 '빈칸'이 되어 학생이 직접 채웁니다(en 의 [[ ]]는 오역 주의 지점으로 강조 표시). "
        "'해석 어려운/오역 위험 부분'이란: 다의어(문맥상 특수한 뜻)·구문 오인(수식 범위·비교 대상·도치·"
        "생략·관계사)·수동태 방향·지칭(대명사가 가리키는 것)·관용표현/구동사·부정/이중부정·연결어의 논리 "
        "방향 등입니다. [[ ]] 범위는 '단어~구~조각 통째'까지 자유롭게 정하세요 — 너무 잘게(단어 하나씩)만 "
        "뚫으면 해석 연습이 부족하니, 해석이 까다로운 곳은 '의미 있는 구·절 덩어리'나 '조각 통째'를 빈칸으로 "
        "두어 학생이 충분히 써 보게 하세요. 한 문장에서 1~3곳, 쉬운 부분은 감싸지 마세요.\n"
        "- misreads(내용 확인 — '이렇게 읽으면 오답'): 이 문장의 '의미(내용)'를 잘못 이해한 진술 1~2개를 "
        "만드세요. 모두 '틀린(X)' 진술이어야 합니다(정답은 넣지 마세요). '단어 번역 실수(어휘·직역)'는 넣지 "
        "마세요 — 해석 난이도는 위 끊어읽기 빈칸이 담당합니다.\n"
        "  ★ 목표: 학생이 이 '오답 찾기'만 풀어도 '필자의 의견 / 함축의미 / 지칭'을 알게 되도록 만드세요. "
        "즉 오답과 그 해설(why)이 아래 셋 중 그 문장에 해당하는 것을 자연스럽게 짚어야 합니다:\n"
        "   · 필자의 의견: 이 문장에서 필자가 긍정/부정/중립 어느 태도인지, 무엇을 주장·평가하는지\n"
        "   · 함축의미: 표면 뜻 너머 '숨은 뜻·의도'(비유·반어·강조가 실제로 뜻하는 바)\n"
        "   · 지칭: 대명사·지시어(it/this/those/they 등)나 표현이 '무엇을 가리키는지'\n"
        "  오답 유형(그 문장에 성립하는 것으로): 반대로 이해(긍↔부·원인↔결과) / 역할 착각(주제↔근거) / "
        "비교 오해 / 범위 오류(과잉일반화) / 초점 이탈 / 지칭 오인 / 함축 무시(직역만).\n"
        "  각 항목: statement(그럴듯하지만 의미가 틀린 진술 한 줄), "
        "why(왜 틀렸는지 + '바른 의미'를 쉬운 말로 — 필자 의견/함축의미/지칭 중 해당하는 것이 드러나게).\n"
    )
