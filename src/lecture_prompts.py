"""'강의컨셉 교재(필생보 스타일)' 생성 프롬프트.

원칙:
- 학생이 '문제를 풀며 스스로 학습'하도록 설계한다(예측·해석을 직접 하게 함).
- 강사는 답지(끊어읽기·캐치·요지)로 함께 맞춰본다.
- 문장 번호(1..n)는 코드가 매겨 프롬프트에 넣어 주고, LLM 은 그 번호를 그대로 사용한다.
- 응답은 구조화된 JSON(스키마)으로 강제한다. 지문에 실제로 있는 내용만 쓴다.
- 2단계 호출: (1) 개관(Overview) → (2) 문장별 분석(SentenceAnalysis).
"""
from __future__ import annotations

from .lecture_schemas import STANCES, STRUCTURES, LectureSentence

SYSTEM = (
    "당신은 한국 고등학교 영어 내신·수능 지문으로 '필자의 생각이 보이는 영어독해' 워크북을 "
    "만드는 전문 강사입니다. 학생이 스스로 예측·해석하도록 문제를 설계하고, 강사가 함께 맞춰볼 "
    "정확한 답지를 만듭니다. 담백하고 자연스러운 설명체(교사 말투)를 쓰되 억지 유행어·이모지는 "
    "쓰지 마세요. 지문에 실제로 있는 내용만 근거로 하고, 요청된 JSON 스키마에 정확히 맞는 "
    "JSON 으로만 응답하세요."
)


def _numbered(sentences: list[LectureSentence]) -> str:
    return "\n".join(f"{s.id} {s.text}" for s in sentences)


# 1차: 지문 전체 개관 ---------------------------------------------------------
def overview_prompt(title: str, sentences: list[LectureSentence]) -> str:
    n = len(sentences)
    return (
        f"[지문 제목] {title}\n\n"
        f"[지문 — 문장 번호가 매겨져 있음 (총 {n}문장)]\n{_numbered(sentences)}\n\n"
        "위 지문의 '전체 개관'을 만드세요. (학생 예측 정답 + 답지에 쓸 요소)\n\n"
        "- theme_ko: 이 지문의 주제를 나타내는 '한글 명사구' 제목"
        "(예: '두려움이 영장류·아기의 사회성 발달을 늦추는 이유'). 완결 문장이 아니라 제목다운 명사구로.\n"
        "- topic(🔎 소재): 이 지문이 '무엇에 관한 글인지' 한 줄로.\n"
        f"- stance(🗗 필자 주장): 다음 중 하나만 — {' / '.join(STANCES)}.\n"
        "- stance_reason: 평가어(형용사)·마지막 문장 등 근거를 한 줄로. "
        "(긍정=좋다·이롭다·중요/should·valuable·effective, 부정=문제·해롭다/But·However·fail·overlook, "
        "중립=사실 설명·양쪽 비교만)\n"
        f"- structure(🧩 글의 구조): 다음 중 하나만 — {' / '.join(STRUCTURES)}.\n"
        "- structure_reason: 그렇게 본 근거를 전환·연결표현이나 문장 번호로 한 줄.\n"
        "- restatement_chains(🔗 재진술 사슬): 2~3개. 지문에서 '같은 개념'이 서로 다른 표현으로 "
        "반복·변주되는 흐름을 찾으세요. 각 사슬은 label(그 개념의 한글 이름), "
        "expressions(지문에 나온 순서대로의 '영어 표현' 2개 이상, 지문에 실제로 있는 표현 그대로), "
        "variation(추상→구체 등 어떻게 바뀌어 가는지 한 줄).\n"
        "- analogy_name(💡 이 지문의 비유): 지문 전체를 하나로 꿰는 쉬운 일상 비유의 이름"
        "(예: '놀이터 벤치', '가족사진 프레임', '골대 옮기기'). 짧은 명사구로.\n"
        "- analogy_desc: 그 비유를 지문 전체 흐름에 어떻게 대응시키는지 한 줄로.\n"
        "- gist(✅ 전체 요지): 지문 전체 요지를 학생에게 설명하듯 한두 문장으로.\n"
    )


# 2차: 문장별 분석 ------------------------------------------------------------
def sentence_prompt(title: str, sentences: list[LectureSentence],
                    analogy_name: str, analogy_desc: str) -> str:
    n = len(sentences)
    return (
        f"[지문 제목] {title}\n"
        f"[이 지문의 비유] {analogy_name} — {analogy_desc}\n\n"
        f"[지문 — 문장 번호가 매겨져 있음 (총 {n}문장)]\n{_numbered(sentences)}\n\n"
        f"[A] sentences — 위 {n}개 문장을 '한 문장도 빠짐없이(id 1~{n} 전부)' 분석해 순서대로 담으세요.\n"
        "각 문장 항목:\n"
        "- id: 위 문장 번호 그대로.\n"
        "- english: 그 문장의 원문 전체를 첫 단어부터 마침표까지 그대로.\n"
        "- syntax_tag: 그 문장의 핵심 구문·문법을 짧게(예: '관계사절(play a role)·분사구', "
        "'비교급 than절 도치·생략', '분사구문(believing)/keep+O+부사'). 특별한 게 없으면 빈 문자열.\n"
        "- vocab(📘 어휘): 그 문장에서 학생이 모를 만한 핵심 단어·표현 2~5개를 {word, meaning}로. "
        "쉬운 단어는 빼고, 다의어·숙어·수준 높은 어휘 위주로.\n"
        "- chunks(④ 끊어읽기): 문장을 의미 단위로 끊어, 각 조각을 {en(영어 조각), ko(그 조각의 직독직해 "
        "한국어)}로. chunks 의 en 을 순서대로 이으면 그 문장의 english 와 정확히 같아야 하며, "
        "특히 문장 맨 앞 주어·동사를 첫 chunk 에 반드시 포함하세요. ko 는 그 조각만의 직독직해"
        "(문장 전체 완역이 아니라 조각별 끊어읽기 해석).\n"
        "- catch(✅ 이 정도는 캐치): 필자가 '이 문장으로 하고 싶은 말'을 한 줄로"
        "(주제 제시/근거/예시/전환/결론 등 글에서의 역할이 드러나게).\n"
        "- easy_example(💡 쉬운 예시): 위 '이 지문의 비유'를 이 문장 내용에 대응시킨 쉬운 예시를 한 줄로. "
        "모든 문장의 easy_example 이 같은 비유(예: 놀이터 벤치)로 일관되게 이어지도록 쓰세요.\n\n"

        "[B] problems — '오역 위험이 큰 지점'만 골라 3~6개의 문제를 만드세요. "
        "학생이 지문 전체 해석을 일일이 적는 대신, 틀리기 쉬운 핵심만 '객관식 또는 짧은 주관식'으로 "
        "풀면 그 지문 공부가 끝나도록 설계합니다. 지문에 실제로 있는 표현만 대상으로 하세요.\n"
        "- 대상: 다의어(문맥상 다른 뜻)·구조 오인(수식 범위·비교 대상·도치/생략)·수동태 방향·지칭"
        "(대명사 one/it/this 등이 가리키는 대상)·관용표현·연결어 반전 등 오역이 잘 나는 곳.\n"
        "- 각 문제: no(1부터), sentence_id(대상 문장 번호), focus(밑줄 대상이 되는 '영어 구/표현' "
        "그대로), kind('객관식' 또는 '주관식'), question(발문), explanation(왜 그 오답이 틀렸는지·정답 근거).\n"
        "- kind='객관식': options 에 한국어 해석 선지 3개 안팎(2~4개)을 담되 '오답은 학생이 흔히 하는 오역', "
        "정답은 1개. answer_index 에 정답 위치(0부터)를 정확히. answer_text 에는 정답 선지 내용을 그대로.\n"
        "- kind='주관식': options 는 빈 배열, answer_index 는 -1. question 은 '짧게 답할 수 있는' 형태로"
        "(예: '밑줄 친 one 이 가리키는 대상을 우리말로 쓰시오', 'than 이하 비교 대상을 우리말로 쓰시오', "
        "'밑줄 친 부분을 우리말로 해석하시오'). answer_text 에 모범 답(짧게).\n"
        "- 유형이 한쪽에 치우치지 않게 객관식과 주관식을 섞고, 서로 다른 문장을 고르게 다루세요.\n"
    )
