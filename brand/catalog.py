"""Ortica 자료·교재 카탈로그.

이미지와 블로그 원고가 모두 이 파일을 읽는다. 문구를 고칠 곳은 여기 한 곳뿐.
`price` 는 비워 두었다. 값을 넣으면 상세페이지와 가격표 이미지에 함께 나온다.
근거와 검토할 항목은 `brand/PRICING.md` 참고.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Item:
    key: str                     # 파일 이름에 쓰는 영문 키
    no: str                      # 라인업 번호 (01~)
    name: str                    # 자료 이름
    en: str                      # 영문 표기 (장식용)
    one_line: str                # 한 줄 정의
    lead: str                    # 상세 첫 문단 (2~3문장)
    points: list = field(default_factory=list)
    # ↑ (소제목, 설명) 또는 (소제목, 설명, 부분확대 파일명).
    #   지면 전체를 넣으면 글자가 작아 아무것도 안 읽힌다. 특징 하나에 그 특징이
    #   보이는 자리만 잘라 붙인다. 파일은 pdf_samples.CROPS 가 만든다.
    spec: list[tuple[str, str]] = field(default_factory=list)     # (항목, 값)
    who: list[str] = field(default_factory=list)                  # 이런 분께
    price: str = ""              # 표기용 가격 문자열
    price_note: str = ""         # 가격 아래 단서
    sample: str = ""             # brand/assets/samples/ 안의 실제 산출물 예시 파일명
    sample_note: str = ""        # 예시 이미지 아래 설명
    thumb: str = ""              # 라인업 썸네일만 다른 사진을 쓸 때. 비면 sample
    # ↑ 나란히 붙인 비교 사진처럼, 작게 줄이면 뭉개지는 장이 있다
    thumbs: list[tuple[str, str]] = field(default_factory=list)  # (파일명, 라벨)
    # ↑ 판형이 여럿인 자료는 라인업에서도 그 판형을 나란히 놓는다. 하나만 놓으면
    #   '세 가지 중에 고르세요'라고 써 놓고 한 가지만 보여 주는 꼴이 된다
    extra: list[tuple[str, str]] = field(default_factory=list)  # (예시 파일명, 설명) 추가 장
    max_points: int = 0          # 특징 줄 수. 0이면 build.MAX_POINTS
    opening: str = ""            # 차별점 바로 아래에 크게 놓는 지면 한 장
    opening_note: str = ""       # ↑ 그 아래 한 줄
    lineup_note: str = ""        # 라인업 부제 아래 한 줄 더. 목록에서만 쓴다
    lineup_line: str = ""        # 라인업 줄에만 다르게 쓰는 부제. 비면 one_line
    # ↑ 상세페이지는 한 줄과 강조 줄이 따로 서지만, 목록에는 한 줄만 들어간다.
    #   목록에서 더 중요한 말이 따로 있을 때 여기에 적는다
    points_title: str = ""       # 특징 묶음 위에 다는 제목. 비면 제목 없이 바로
    lineup_points: int = 0       # 라인업 줄에 보일 특징 수. 0이면 두 줄
    # ↑ 셋 이상이면 소제목만 짧게 늘어놓는다. 설명까지 다 넣으면 목록이 늘어진다
    lineup_bullets: list[tuple[str, str]] = field(default_factory=list)
    # ↑ 목록에만 쓰는 짧은 특징 줄 (소제목, 한 줄). 채우면 points 대신 이걸 쓴다.
    #   설계가 유형마다 다른 자료는 상세 문구를 잘라 붙여서는 두 줄밖에 못 담는다
    figures: int = 0             # 상세페이지에 넣을 사진 수. 0이면 build.MAX_FIGURES
    # ↑ 판형이 여럿인 자료는 그 판형을 다 보여 줘야 무슨 말인지 통한다
    signature: bool = False      # 시그니처 자료. 소개 이미지를 따로 크게 만든다
    made_to_order: bool = False  # 받아 놓고 파는 게 아니라 주문받아 만드는 자료
    grids: list[tuple[str, list[tuple[str, str]]]] = field(default_factory=list)
    # ↑ 항목이 열 개를 넘어가는 표. 두 칸으로 접어 놓는다. 줄줄이 세우면
    #   그 표만 한 화면을 먹는다
    tables: list[tuple[str, list[tuple[str, str]]]] = field(default_factory=list)
    # ↑ (표 제목, [(왼쪽 칸, 오른쪽 설명)]) — 회차 구성·난이도 기준처럼 줄글로 풀면
    #   안 읽히는 것을 표로 보여 준다
    gallery: list[tuple[str, str]] = field(default_factory=list)
    # ↑ (조각 파일명, 라벨) — 유형이 여럿인 자료의 '전부 펼쳐 보기'. 두 칸으로
    #   흘려 놓는다. 이름만 늘어놓으면 어떻게 생겼는지가 안 남는다
    gallery_title: str = ""      # ↑ 그 묶음 제목
    edge: str = ""               # 이 자료 한 줄 차별화 (카드 아래에 굵게)


